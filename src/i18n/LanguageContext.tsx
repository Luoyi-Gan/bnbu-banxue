const messages: Record<Language, Record<TranslationKey, string>> = { zh, en }

interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
  t: (key: string, values?: Record<string, string | number>) => string
  message: (ref?: { key: string; values?: Record<string, string | number> }, fallback?: string) => string
  localize: (value: string) => string
  formatDateTime: (value: string, options?: Intl.DateTimeFormatOptions) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'zh'
  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en' ? 'en' : 'zh'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage)
  const setLanguage = useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage)
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage)
  }, [])
  const toggleLanguage = useCallback(() => setLanguage(language === 'zh' ? 'en' : 'zh'), [language, setLanguage])
  const t = useCallback((key: string, values?: Record<string, string | number>) => {
    const template = messages[language][key as TranslationKey] ?? messages.zh[key as TranslationKey] ?? key
    return Object.entries(values ?? {}).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), template)
  }, [language])
  const message = useCallback((ref?: { key: string; values?: Record<string, string | number> }, fallback?: string) => {
    if (!ref) return fallback ?? ''
    const seed = resolveSeedMessage(ref.key, language)
    if (seed !== undefined) return seed
    if (ref.key === 'legacy.localized') return localizeLegacyText(String(ref.values?.text ?? fallback ?? ''), language)
    return t(ref.key, ref.values)
  }, [language, t])
  const formatDateTime = useCallback((value: string, options?: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(language === 'zh' ? 'zh-CN' : 'en-US', options ?? { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(value)), [language])
  const localize = useCallback((text: string) => localizeLegacyText(text, language), [language])
  const value = useMemo(() => ({ language, setLanguage, toggleLanguage, t, message, localize, formatDateTime }), [language, setLanguage, toggleLanguage, t, message, localize, formatDateTime])

  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
  }, [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider')
  return context
}

